(function () {
  let _lang = 'en';
  try { _lang = localStorage.getItem('jun_lang') || 'en'; } catch (_) {}
  if (!window.TRANSLATIONS[_lang]) _lang = 'en';

  window.currentLang = _lang;

  window.t = function (key) {
    const keys = key.split('.');
    let node = window.TRANSLATIONS[window.currentLang];
    for (const k of keys) { if (node == null) break; node = node[k]; }
    if (node != null) return node;
    node = window.TRANSLATIONS.en;
    for (const k of keys) { if (node == null) break; node = node[k]; }
    return node != null ? node : key;
  };

  window.setLang = function (lang) {
    if (!window.TRANSLATIONS[lang]) return;
    window.currentLang = lang;
    try { localStorage.setItem('jun_lang', lang); } catch (_) {}
    window.applyLang();
    const toggle = document.getElementById('lang-toggle');
    if (toggle) toggle.textContent = lang === 'en' ? 'ภาษาไทย' : 'English';
  };

  window.applyLang = function () {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const val = window.t(el.dataset.i18n);
      if (val != null) el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const val = window.t(el.dataset.i18nPh);
      if (val != null) el.placeholder = val;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const val = window.t(el.dataset.i18nHtml);
      if (val != null) el.innerHTML = val.replace(/\n/g, '<br>');
    });
  };

  window.addEventListener('DOMContentLoaded', () => {
    window.applyLang();
    const toggle = document.getElementById('lang-toggle');
    if (toggle) toggle.textContent = window.currentLang === 'en' ? 'ภาษาไทย' : 'English';
  });
})();
